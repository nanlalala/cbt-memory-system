"""Build a platform-specific wheel/hash lock using official PyPI metadata.

Only explicit, already-pinned versions in requirements-test.in are downloaded.
No model dependencies or paid services are involved.  Every downloaded wheel's
content digest must match its published PyPI release metadata before writing.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import platform
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from urllib.parse import urlparse
from urllib.request import Request, urlopen


ROOT = Path(__file__).resolve().parents[1]
TARGET = "CPython 3.12 / Linux x86_64 / Ubuntu 24.04 (glibc 2.39)"
PIN_RE = re.compile(r"^([A-Za-z0-9_.-]+)==([A-Za-z0-9_.+-]+)$")


def _normalise(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _release_metadata(name: str, version: str) -> tuple[str, dict]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    request = Request(url, headers={"User-Agent": "cbt-memory-test-lock/1"})
    with urlopen(request, timeout=60) as response:
        if urlparse(response.url).hostname != "pypi.org":
            raise RuntimeError("Unexpected metadata redirect outside official PyPI")
        metadata = json.load(response)
    if _normalise(metadata["info"]["name"]) != _normalise(name):
        raise RuntimeError(f"Name mismatch in release metadata: {name}")
    if metadata["info"]["version"] != version:
        raise RuntimeError(f"Version mismatch in release metadata: {name}=={version}")
    return url, metadata


def _supported_wheel(filename: str) -> bool:
    """Permit only portable pure wheels or Linux wheels usable on Ubuntu 24.04."""

    platform_tags = filename[:-4].rsplit("-", 1)[-1].split(".")
    if platform_tags == ["any"]:
        return True
    for tag in platform_tags:
        match = re.fullmatch(r"manylinux_2_(\d+)_x86_64", tag)
        if match and int(match.group(1)) <= 39:
            return True
        if tag in {"manylinux1_x86_64", "manylinux2010_x86_64", "manylinux2014_x86_64"}:
            return True
    return False


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare regenerated outputs without modifying files.")
    args = parser.parse_args(argv)
    if (
        sys.implementation.name != "cpython"
        or sys.version_info[:2] != (3, 12)
        or sys.platform != "linux"
        or platform.machine() != "x86_64"
    ):
        raise SystemExit(f"Generate this lock only on {TARGET}")

    pins = []
    for line in (ROOT / "requirements-test.in").read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        match = PIN_RE.fullmatch(line)
        if not match:
            raise SystemExit(f"Expected exact name==version pin, got: {line}")
        pins.append(match.groups())
    if len({_normalise(name) for name, _ in pins}) != len(pins):
        raise SystemExit("Duplicate dependency pins")

    lock_lines = [
        "# Generated by tools/lock_test_environment.py; do not hand-edit digests.",
        f"# Target: {TARGET}",
        "# Wheels only; each SHA-256 was matched against official PyPI release JSON.",
        "# Exact direct/transitive versions are maintained in requirements-test.in.",
        "--index-url https://pypi.org/simple",
        "--only-binary=:all:",
        "",
    ]
    sources = {"target": TARGET, "metadata_api": "https://docs.pypi.org/api/json/", "packages": []}
    with tempfile.TemporaryDirectory(prefix="cbt-test-lock-") as temporary:
        wheel_dir = Path(temporary)
        subprocess.run(
            [
                sys.executable, "-m", "pip", "--isolated", "download",
                "--index-url", "https://pypi.org/simple", "--only-binary=:all:",
                "--no-deps", "--no-cache-dir", "--dest", str(wheel_dir),
                "--requirement", str(ROOT / "requirements-test.in"),
            ], check=True,
        )
        wheels = list(wheel_dir.glob("*.whl"))
        if len(wheels) != len(pins):
            raise RuntimeError("Expected one compatible wheel for every explicit pin")
        for name, version in pins:
            metadata_url, metadata = _release_metadata(name, version)
            matches = [
                (wheel, item)
                for wheel in wheels
                for item in metadata["urls"]
                if item["filename"] == wheel.name and item["packagetype"] == "bdist_wheel"
            ]
            if len(matches) != 1:
                raise RuntimeError(f"Expected one downloaded PyPI wheel for {name}=={version}")
            wheel, published = matches[0]
            if published["yanked"] or not _supported_wheel(wheel.name):
                raise RuntimeError(f"Yanked or unsupported wheel: {wheel.name}")
            if urlparse(published["url"]).hostname != "files.pythonhosted.org":
                raise RuntimeError(f"Unexpected official wheel host: {published['url']}")
            with wheel.open("rb") as artifact:
                digest = hashlib.file_digest(artifact, "sha256").hexdigest()
            if digest != published["digests"]["sha256"]:
                raise RuntimeError(f"Downloaded content differs from PyPI release digest: {wheel.name}")
            lock_lines.extend([
                f"# wheel: {wheel.name}",
                f"{name}=={version} \\",
                f"    --hash=sha256:{digest}",
                "",
            ])
            sources["packages"].append({
                "name": name,
                "version": version,
                "metadata_url": metadata_url,
                "wheel_filename": wheel.name,
                "wheel_url": published["url"],
                "sha256": digest,
                "requires_python": published["requires_python"],
            })
            print(f"Verified official PyPI wheel: {name}=={version} / {wheel.name}")

    outputs = {
        ROOT / "requirements-test.lock": "\n".join(lock_lines),
        ROOT / "docs/test-environment-sources.json": json.dumps(sources, indent=2) + "\n",
    }
    for destination, content in outputs.items():
        if args.check:
            if destination.read_text() != content:
                raise SystemExit(f"Lock/provenance differs: {destination.relative_to(ROOT)}")
        else:
            destination.write_text(content)
        print(f"{'Checked' if args.check else 'Wrote'}: {destination.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
