"""Generate the fictional readout example with the actual product and renderer.

Run with Python from any directory. This software fixture calls no model,
network or Secret. Its dates and utterances are explicitly invented.
"""
from pathlib import Path
import json
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[2]
for relative in ('modules/agent-integration','modules/long-term-memory/schema',
                 'modules/long-term-memory/storage','modules/long-term-memory/lifecycle',
                 'modules/long-term-memory/extraction','modules/long-term-memory/retrieval'):
    sys.path.insert(0,str(ROOT/relative))

from controlled_dialogue import ControlledDialogueSession, SYSTEM
from cbt_context import POLICY_VERSION, build_cbt_context


def main():
    out=Path(__file__).parent
    texts=['我同意每周做两次想法记录。','想法记录累计做了一次。','这周暂停','想法记录现在怎么安排？']
    rows=[]
    with tempfile.TemporaryDirectory() as folder:
        session=ControlledDialogueSession.open(str(Path(folder)/'fictional.sqlite'),approved_root=folder,
            user_id='fictional-readout-person',run_id='fictional-docs-v4',provider=None,background=False)
        try:
            for index,text in enumerate(texts):
                stamp=f'2026-11-0{3+index}T09:00:00Z'
                reply=session.send_message(text,input_id=f'fictional-{index}',as_of=stamp)
                source=session.durable.get_source(session.user_id,reply['source_commit']['source_id'])
                rows.append(source)
            task=session._task_for_input(texts[-1],stamp)
            bundles,_,state=session._bundles(texts[-1],as_of=stamp,current_source=source,task=task)
            registry,recent,recent_ids,items,_=session._context_readout(
                as_of=stamp,current_source=source,bundles=bundles,task_snapshot=task)
            package=build_cbt_context([
                {'role':'system','content':SYSTEM+'\nKnowledge status: '+reply['knowledge_status']},
                {'role':'user','content':texts[-1]}],bundles,source_registry=registry,subject_id=session.user_id,
                max_outbound_chars=18000,max_response_tokens=1024,
                request_metadata={'model':'deepseek-v4.1-flash','temperature':0,'thinking':{'type':'disabled'}},
                contextual_items=items,recent_messages=recent,recent_source_ids=recent_ids,
                current_source_id=source['source_id'])
            input_record={'scope':'entirely fictional software fixture; dates are declared invented example dates',
                          'sources':rows,'task_state':state,'model_calls':0}
            for name,value in [('fictional-input',input_record),('fictional-request',package.request_payload),
                               ('fictional-trace',package.trace)]:
                (out/(name+'.json')).write_text(json.dumps(value,ensure_ascii=False,indent=2)+'\n')
            (out/'fictional-request.wire.json').write_text(package.serialized_request)
            messages='\n\n'.join(f'### Message {index} · {message["role"]}\n\n```text\n{message["content"]}\n```'
                for index,message in enumerate(package.messages,1))
            guide=f'''# Fictional renderer request

This complete request was generated by `render_example.py` through the actual
file-backed task projector and `build_cbt_context`. The utterances and dates are
invented software fixtures. No model, external dataset, network or Secret is used.
This example demonstrates interface behavior and has no response-quality score.

## Transformation and scope

The source sequence agrees to two thought records, reports one completed record,
then pauses further practice. The real task projector preserves acceptance,
participation, target and reported count as independent supported fields. The
renderer includes these fields, their source evidence and a provisional pause-aware
next-move suggestion. Unreported learning, emotion ratings and beliefs stay unknown.

Only available recent original messages appear in this offline example. There is
no retained model reply to rehydrate as a recent assistant message. Production
assistant history requires a live retained response receipt, source dependencies,
object versions and operational chronology.

| Layer | Fields in the linked artifacts |
| --- | --- |
| Stored sources and state | `fictional-input.json` preserves roles, fixture times, permissions and actual projected task axes |
| Dynamic model reference | `claims`, `action_plans`, `source_reports`, `turn_guidance`, `recent_sources` and `current_input_source` |
| External audit | `fictional-trace.json` preserves hashes, item ranks, selected/omitted identities and version dependencies |

The request uses policy `{POLICY_VERSION}` and {package.char_count:,} escaped JSON
characters under an 18,000-character example ceiling. Token usage is unknown
because no model ran. The readable JSON file and exact serialized wire JSON are
both retained. The wire-file SHA-256 equals the trace request hash.

The rerun comparison has three conditions, `no_rag`, `raw_history_rag` and
`managed_memory_rag`. Each receives the same complete CBT counselor policy.
The first receives recent context and the current request; the second adds
selected original history; the third adds selected supported processed memory
and necessary evidence. The example below shows the managed condition only.

## Complete messages

{messages}
'''
            (out/'FICTIONAL_REQUEST.md').write_text(guide)
            print(json.dumps({'policy_version':POLICY_VERSION,'request_chars':package.char_count,
                              'roles':[m['role'] for m in package.messages],'model_calls':0}))
        finally:
            session.close()


if __name__=='__main__':
    main()
